import dotenv from 'dotenv';
dotenv.config();

import { EntryModel } from './models/index.js';

async function testAirplaneModeWorkflow() {
  console.log('--- Commencing Airplane-Mode Offline & Sync Verification ---');
  const base = 'http://localhost:5000/api';

  // 1. Authenticate as Nurse Rekha
  const loginRes = await fetch(`${base}/auth/login`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ email: 'nurse@thecarepal.com', password: 'NursePass123!' })
  });
  const { token, user } = await loginRes.json();
  console.log('1. Nurse authenticated:', user.name, '| Role:', user.role);

  // 2. Simulate 3 offline-generated entries on the device (as generated by addToOfflineQueue)
  const clientTag = 'airplanemode_test_' + Date.now();
  const offlineEntries = [
    {
      kind: 'vital',
      day: '2026-11-17',
      time: '15:40',
      clientId: `${clientTag}_1`,
      data: { vitalType: 'pulse', value: 76, unit: 'bpm' }
    },
    {
      kind: 'meal',
      day: '2026-11-17',
      time: '15:45',
      clientId: `${clientTag}_2`,
      data: { mealType: 'snack', items: 'Fresh coconut water & 2 biscuits', portion: 'all', waterMl: 200 }
    },
    {
      kind: 'activity',
      day: '2026-11-17',
      time: '15:50',
      clientId: `${clientTag}_3`,
      data: { activityType: 'Walk', minutes: 15, notes: 'Brief afternoon balcony walk' }
    }
  ];
  console.log('2. Simulated device in Airplane Mode: 3 care entries queued in local storage.');

  // 3. Reconnect & Flush Queue (First Sync)
  console.log('3. Reconnecting network: Flushing offline queue to server...');
  let firstSyncCount = 0;
  for (const item of offlineEntries) {
    const res = await fetch(`${base}/patients/patient_kamla_01/entries`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${token}`
      },
      body: JSON.stringify(item)
    });
    if (res.ok) {
      firstSyncCount++;
    }
  }
  console.log(`   First sync completed: ${firstSyncCount}/3 entries persisted to server.`);

  // Verify in database
  const countInDb = await EntryModel.countDocuments({
    clientId: { $in: [`${clientTag}_1`, `${clientTag}_2`, `${clientTag}_3`] }
  });
  console.log(`   Count in database: ${countInDb} (Expected: 3)`);

  // 4. Retry sync / duplicate packet test (Airplane-mode reconnect glitch test)
  console.log('4. Testing de-duplication: Sending the exact same 3 entries again (simulating network retry)...');
  let duplicatePreventedCount = 0;
  for (const item of offlineEntries) {
    const res = await fetch(`${base}/patients/patient_kamla_01/entries`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${token}`
      },
      body: JSON.stringify(item)
    });
    const data = await res.json();
    if (data.deduplicated) {
      duplicatePreventedCount++;
    }
  }
  console.log(`   De-duplication caught: ${duplicatePreventedCount}/3 retried packets.`);

  // Verify final count in database
  const finalCountInDb = await EntryModel.countDocuments({
    clientId: { $in: [`${clientTag}_1`, `${clientTag}_2`, `${clientTag}_3`] }
  });
  console.log(`   Final count in database: ${finalCountInDb} (Must remain exactly 3, zero duplicates!)`);

  if (finalCountInDb === 3 && countInDb === 3 && duplicatePreventedCount === 3) {
    console.log('🎉 AIRPLANE-MODE TEST PASSED 100%!');
  } else {
    console.error('❌ De-duplication check failed');
  }
}

testAirplaneModeWorkflow().catch(console.error);
